class FeeStructure(models.Model):
    classroom = models.ForeignKey(ClassRoom, on_delete=models.SET_NULL, null=True, blank=True)
    term = models.CharField(max_length=20, default="Term 3")
    year = models.CharField(max_length=10, default="2026")
    tuition = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    lunch = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    transport = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    boarding = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    exam = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    activity = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    uniform = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    books = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    computer = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    medical = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    development = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    other = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    other_label = models.CharField(max_length=100, blank=True, default="")
    notes = models.TextField(blank=True, default="")
    @property
    def total(self): return float(self.tuition or 0)+float(self.lunch or 0)+float(self.transport or 0)+float(self.boarding or 0)+float(self.exam or 0)+float(self.activity or 0)+float(self.uniform or 0)+float(self.books or 0)+float(self.computer or 0)+float(self.medical or 0)+float(self.development or 0)+float(self.other or 0)
    def __str__(self): return f"{self.classroom} - {self.term} {self.year} - KSh {self.total}"

