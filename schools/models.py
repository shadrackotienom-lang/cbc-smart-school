class UserProfile(models.Model):
    ROLE_CHOICES = [('Admin','Admin / Head Teacher'),('Teacher','Teacher'),('Learner','Learner / Student'),('Parent','Parent / Guardian'),('Bursar','Bursar / Accountant'),('Matron','Matron / Patron - Boarding'),('Other','Other Staff')]
    user = models.OneToOneField(User, on_delete=models.CASCADE, related_name='profile')
    role = models.CharField(max_length=20, choices=ROLE_CHOICES, default='Admin')
    learner = models.ForeignKey(Learner, on_delete=models.SET_NULL, null=True, blank=True, verbose_name="Link to Learner (if Learner / Parent)")
    phone = models.CharField(max_length=20, blank=True, default="")
    def __str__(self): return f"{self.user.username} - {self.role}"